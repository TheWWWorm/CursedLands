"""Generate verified cover-family masks from pinned editor metadata.

Usage: python3 tools/benchmarks/biome_cover_metadata.py RENDERER_REPO CENSUS_JSON OUTPUT_GD
Census hashes original 512x512 RGBA8 images without mipmaps. No texture bytes
are embedded. Each byte describes one atlas slot: low four bits are bare
soil/rock/paving corners; high four bits are sand corners (NW, NE, SE, SW in
the original atlas UV convention). Unknown families/corners remain unset.
"""
import base64
import json
from pathlib import Path
import re
import subprocess
import sys

revision = '0092dc6e1d7c4aab3f74644a79e9bfca11ecf293'
repo, census_file, output = map(Path, sys.argv[1:])
source = subprocess.check_output(['git', '-C', str(repo), 'show', revision + ':Source/terrain_tile_presets.h'], text=True)
census = json.loads(census_file.read_text())
identities = {}
for name, count, encoded, families in re.findall(r'\{"([^"]+)", (\d+), "([^"]+)", "([^"]+)"\}', source):
    if name.lower() not in census:
        continue
    names = {int(k): v.lower().split(' /', 1)[0] for k, v in (part.split('=', 1) for part in families.split(';') if part)}
    signatures = base64.b64decode(encoded)
    assert len(signatures) == int(count) * 4
    masks = bytearray()
    for slot in range(int(count)):
        mask = 0
        for corner, family in enumerate(signatures[slot * 4:slot * 4 + 4]):
            word = names.get(family, '')
            # Explicit names keep future/unrecognized editor families neutral.
            if word in ('ground', 'soil', 'stone', 'rock', 'paving', 'slabs', 'rubble', 'lava'):
                mask |= 1 << corner
            if word == 'sand':
                mask |= 1 << (corner + 4)
        masks.append(mask)
    for atlas in census[name.lower()]:
        assert (atlas['width'], atlas['height'], atlas['mips']) == (512, 512, False)
        offset = atlas['atlas'] * 64
        packed = bytes(masks[offset:offset + 64])
        assert len(packed) == 64
        digest = atlas['sha256']
        if digest in identities:
            # A few editor profiles disagree about identical art. Leave the
            # whole disputed slot neutral rather than picking a profile name.
            identities[digest]['uncertain'].update(i for i in range(64) if identities[digest]['masks'][i] != packed[i])
            identities[digest]['profiles'].append(name + ':' + str(atlas['atlas']))
        else:
            identities[digest] = {'masks': packed, 'profiles': [name + ':' + str(atlas['atlas'])], 'uncertain': set()}
for row in identities.values():
    row['masks'] = bytes(0 if i in row['uncertain'] else m for i, m in enumerate(row['masks']))
lines = ['extends RefCounted', '## Verified original atlas identities; modified/unknown images add no rules.',
         '## Generated by tools/benchmarks/biome_cover_metadata.py from renderer',
         '## '+revision+' Source/terrain_tile_presets.h.',
         '## That table credits ei-mapper-endurance af24d45 editor family metadata.',
         '## Each slot byte: bare NW/NE/SE/SW bits 0..3, sand bits 4..7.',
         'const IDENTITIES := {']
for digest, row in sorted(identities.items()):
    if any(row['masks']):
        lines += ['\t# '+', '.join(row['profiles'])+(' (ambiguous slots omitted: '+str(sorted(row['uncertain']))+')' if row['uncertain'] else ''), '\t"'+digest+'": "'+row['masks'].hex()+'",']
lines += ['}', '', '', 'static func masks(image: Image) -> PackedByteArray:',
          '\tif image==null or image.get_size()!=Vector2i(512,512): return PackedByteArray()',
          '\tvar pixels := image',
          '\tif image.is_compressed() or image.get_format()!=Image.FORMAT_RGBA8 or image.has_mipmaps():',
          '\t\tpixels = image.duplicate() as Image', '\t\tif pixels.is_compressed(): pixels.decompress()',
          '\t\tpixels.clear_mipmaps(); pixels.convert(Image.FORMAT_RGBA8)',
          '\tvar digest := HashingContext.new(); digest.start(HashingContext.HASH_SHA256)',
          '\tdigest.update(pixels.get_data())',
          '\treturn String(IDENTITIES.get(digest.finish().hex_encode(),"")).hex_decode()', '']
output.write_text('\n'.join(lines))
print(json.dumps({'identities': sum(any(v['masks']) for v in identities.values()),
                  'classified_slots': sum(sum(bool(m) for m in v['masks']) for v in identities.values()),
                  'ambiguous_slots_omitted': sum(len(v['uncertain']) for v in identities.values())}))
