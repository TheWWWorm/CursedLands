"""Emit exact authored natural-family corners keyed by original RGBA8 atlas SHA.

Usage: python3 terrain_transition_metadata.py RENDERER_REPO CENSUS_JSON OUTPUT_GD
No map-name inference, nearest-family borrowing, or majority votes. Conflicting
profiles neutralize the complete slot. Water/bed, road and unknown families are
not natural transition inputs, even when their ground-type byte looks natural.
"""
import base64
import json
from pathlib import Path
import re
import subprocess
import sys

REVISION = '0092dc6e1d7c4aab3f74644a79e9bfca11ecf293'
repo, census_file, output = map(Path, sys.argv[1:])
source = subprocess.check_output(['git', '-C', str(repo), 'show', REVISION + ':Source/terrain_tile_presets.h'], text=True)
profiles = re.findall(r'\{"([^"]+)", (\d+), "([^"]+)", "([^"]+)"\}', source)
census = json.loads(census_file.read_text())

def natural(name):
    return name.split(' /', 1)[0] in ('grass', 'snow', 'sand', 'stone', 'rock') and not any(v in name for v in ('water', 'swamp', 'bed'))

names = sorted({part.split('=', 1)[1].lower() for _, _, _, families in profiles
                for part in families.split(';') if part and natural(part.split('=', 1)[1].lower())})
assert len(names) < 64
ids = {name: i + 1 for i, name in enumerate(names)}
identities = {}
for name, count, encoded, families in profiles:
    if name.lower() not in census:
        continue
    mapping = {int(k): ids.get(v.lower(), 0) for k, v in (part.split('=', 1) for part in families.split(';') if part)}
    raw = base64.b64decode(encoded)
    assert len(raw) == int(count) * 4
    signatures = bytes(mapping.get(value, 0) for value in raw)
    for atlas in census[name.lower()]:
        assert (atlas['width'], atlas['height'], atlas['mips']) == (512, 512, False)
        packed = signatures[atlas['atlas'] * 256:(atlas['atlas'] + 1) * 256]
        assert len(packed) == 256
        digest = atlas['sha256']
        if digest not in identities:
            identities[digest] = {'corners': packed, 'profiles': [], 'uncertain': set()}
        row = identities[digest]
        row['profiles'].append(name + ':' + str(atlas['atlas']))
        row['uncertain'].update(i for i in range(64) if row['corners'][i * 4:i * 4 + 4] != packed[i * 4:i * 4 + 4])
for row in identities.values():
    row['corners'] = bytes(0 if i // 4 in row['uncertain'] else value for i, value in enumerate(row['corners']))
lines = ['extends RefCounted',
         '## Exact original-atlas identities; authored NW, NE, SE, SW family corners.',
         '## Generated by tools/benchmarks/terrain_transition_metadata.py from renderer',
         '## ' + REVISION + ' Source/terrain_tile_presets.h,',
         '## which credits ei-mapper-endurance af24d45 editor family metadata.',
         '## Zero is unsupported. Ground/path/liquid/bed and ambiguous slots stay zero.',
         'const FAMILIES := ' + json.dumps([''] + names), 'const IDENTITIES := {']
for digest, row in sorted(identities.items()):
    if any(row['corners']):
        lines += ['\t# ' + ', '.join(row['profiles']) + ('; ambiguous slots omitted: ' + str(sorted(row['uncertain'])) if row['uncertain'] else ''),
                  '\t"' + digest + '": "' + row['corners'].hex() + '",']
lines += ['}', '', '', 'static func corners(image: Image) -> PackedByteArray:',
          '\tif image == null or image.get_size() != Vector2i(512,512): return PackedByteArray()',
          '\tvar pixels := image',
          '\tif image.is_compressed() or image.get_format() != Image.FORMAT_RGBA8 or image.has_mipmaps():',
          '\t\tpixels = image.duplicate() as Image',
          '\t\tif pixels.is_compressed() and pixels.decompress() != OK: return PackedByteArray()',
          '\t\tpixels.clear_mipmaps(); pixels.convert(Image.FORMAT_RGBA8)',
          '\tvar digest := HashingContext.new(); digest.start(HashingContext.HASH_SHA256)',
          '\tdigest.update(pixels.get_data())',
          '\treturn String(IDENTITIES.get(digest.finish().hex_encode(), "")).hex_decode()', '']
output.write_text('\n'.join(lines))
print(json.dumps({'families': len(names), 'identities': sum(any(row['corners']) for row in identities.values()),
                  'ambiguous_slots_omitted': sum(len(row['uncertain']) for row in identities.values())}))
