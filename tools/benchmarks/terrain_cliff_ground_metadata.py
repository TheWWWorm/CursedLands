"""Generate cliff-only dry-ground identities from pinned original tile metadata.

Usage: terrain_cliff_ground_metadata.py RENDERER_REPO CENSUS_JSON OUTPUT_GD
The census contains SHA256 hashes of original 512x512 RGBA8 atlas pixels.
Floor transition classification remains unchanged. Water, underwater artwork,
paving, lava and unknown families are deliberately excluded.
"""
import base64
import json
from pathlib import Path
import re
import subprocess
import sys

REVISION = '0092dc6e1d7c4aab3f74644a79e9bfca11ecf293'
repo, census_path, output = map(Path, sys.argv[1:])
root = Path(__file__).resolve().parents[2]
natural = (root / 'game/src/game/fx/terrain_transition_tiles.gd').read_text()
families = json.loads(re.search(r'const FAMILIES := (\[.*?\])', natural).group(1))
source = subprocess.check_output(['git', '-C', str(repo), 'show',
    REVISION + ':Source/terrain_tile_presets.h'], text=True)
profiles = re.findall(r'\{"([^"]+)", (\d+), "([^"]+)", "([^"]+)"\}', source)
extra = sorted({part.split('=', 1)[1].lower() for _, _, _, names in profiles
    for part in names.split(';') if part and part.split('=', 1)[1].lower().startswith(('ground /', 'rubble /'))
    and 'water' not in part.lower()})
assert len(extra) < 53
codes = {name: index for index, name in enumerate(families) if name}
codes.update({name: 200 + index for index, name in enumerate(extra)})
codes.update({'grass / swamp': 253, 'ground / dirt': 254})
census = json.loads(census_path.read_text())
identities = {}
for name, count, encoded, names in profiles:
    if name.lower() not in census:
        continue
    labels = {int(k): v.lower() for k, v in (part.split('=', 1) for part in names.split(';') if part)}
    corners = base64.b64decode(encoded)
    assert len(corners) == int(count) * 4
    for atlas in census[name.lower()]:
        assert (atlas['width'], atlas['height'], atlas['mips']) == (512, 512, False)
        start = atlas['atlas'] * 256
        row = bytes(codes.get(labels.get(c, ''), 0) for c in corners[start:start + 256])
        assert len(row) == 256
        key = atlas['sha256']
        if key in identities:
            previous, labels_seen = identities[key]
            row = bytes(a if a == b else 0 for a, b in zip(row, previous))
            labels_seen.append(f'{name}:{atlas["atlas"]}')
        else:
            labels_seen = [f'{name}:{atlas["atlas"]}']
        identities[key] = (row, labels_seen)
lines = ['extends RefCounted',
    '## Generated by tools/benchmarks/terrain_cliff_ground_metadata.py.',
    '## Original atlas SHA256 identities and dry ground/rubble corners from',
    '## renderer ' + REVISION + ' Source/terrain_tile_presets.h',
    '## (credits ei-mapper-endurance af24d45). IDs start at 200; no floor rules.',
    'const FIRST_FAMILY := 200', 'const FAMILIES := ' + json.dumps(extra),
    'const IDENTITIES := {']
for key, (row, labels_seen) in sorted(identities.items()):
    if not any(200 <= c < 253 or c == 254 for c in row):
        continue
    lines += ['\t# ' + ', '.join(labels_seen), '\t"' + key + '": "' + row.hex() + '",']
lines += ['}', '']
output.write_text('\n'.join(lines))
print('Generated', sum(1 for line in lines if line.startswith('\t"')), 'dry-ground atlas identities')
