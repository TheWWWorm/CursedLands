"""Generate conservative full-slot sand identities from pinned editor metadata.

Usage: python3 tools/benchmarks/biome_sand_metadata.py RENDERER_REPO CENSUS_JSON OUTPUT_GD
Census hashes canonical 512x512 RGBA8 original images, with no mipmaps.
Original game texture bytes are neither embedded nor changed.
"""
import base64
import json
from pathlib import Path
import re
import subprocess
import sys

revision = '0092dc6e1d7c4aab3f74644a79e9bfca11ecf293'
repo, census_file, output = map(Path, sys.argv[1:])
source = subprocess.check_output(['git', '-C', str(repo), 'show', revision + ':Source/terrain_tile_presets.h'], text=True)
census = json.loads(census_file.read_text())
identities = {}
for name, count, encoded, families in re.findall(r'\{"([^"]+)", (\d+), "([^"]+)", "([^"]+)"\}', source):
    if name.lower() not in census:
        continue
    names = {int(k): v.lower() for k, v in (part.split('=', 1) for part in families.split(';') if part)}
    signatures = base64.b64decode(encoded)
    assert len(signatures) == int(count) * 4
    allowed = [all(names.get(i) in ('sand / yellow', 'sand / dark', 'sand / common grayish')
                   for i in signatures[s * 4:s * 4 + 4]) for s in range(int(count))]
    for atlas in census[name.lower()]:
        assert (atlas['width'], atlas['height'], atlas['mips']) == (512, 512, False)
        offset = atlas['atlas'] * 64
        slots = [i for i in range(64) if allowed[offset + i]]
        digest = atlas['sha256']
        if digest in identities:
            assert identities[digest]['slots'] == slots, 'Conflicting semantic metadata for identical image'
            identities[digest]['profiles'].append(name + ':' + str(atlas['atlas']))
        else:
            identities[digest] = {'slots': slots, 'profiles': [name + ':' + str(atlas['atlas'])]}
lines = ['extends RefCounted', '## Full soft-sand slots only; altered/unknown atlases stay unclassified.',
         '## Generated by tools/benchmarks/biome_sand_metadata.py from renderer',
         '## '+revision+' Source/terrain_tile_presets.h.',
         '## That table credits ei-mapper-endurance af24d45 editor family metadata.',
         '## Fingerprints: original 512x512 RGBA8 pixels without mipmaps.', 'const IDENTITIES := {']
for digest, row in sorted(identities.items()):
    if row['slots']:
        lines += ['\t# '+', '.join(row['profiles']), '\t"'+digest+'": '+str(row['slots'])+',']
lines += ['}', '', '', 'static func slots(image: Image) -> Array:',
          '\tif image==null or image.get_size()!=Vector2i(512,512): return []',
          '\tvar pixels := image',
          '\tif image.is_compressed() or image.get_format()!=Image.FORMAT_RGBA8 or image.has_mipmaps():',
          '\t\tpixels = image.duplicate() as Image', '\t\tif pixels.is_compressed(): pixels.decompress()',
          '\t\tpixels.clear_mipmaps(); pixels.convert(Image.FORMAT_RGBA8)',
          '\tvar digest := HashingContext.new(); digest.start(HashingContext.HASH_SHA256)',
          '\tdigest.update(pixels.get_data())', '\treturn IDENTITIES.get(digest.finish().hex_encode(),[])', '']
output.write_text('\n'.join(lines))
print(json.dumps({'identities': sum(bool(v['slots']) for v in identities.values()), 'slots': sum(len(v['slots']) for v in identities.values())}))
